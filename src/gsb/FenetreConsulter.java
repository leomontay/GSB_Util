    private void jTextRechercheActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jTextRechercheActionPerformed
        String recherche = jTextRecherche.getText() + "%";

        try {
            String sql = "SELECT * FROM utilisateur WHERE nom LIKE ? OR prenom LIKE ? OR login LIKE ? OR id LIKE ? OR ville LIKE ? OR dateEmbauche LIKE ?";
            PreparedStatement statement = accesBdD.getConnexion().prepareStatement(sql);

            for (int i = 1; i <= 6; i++) {
                statement.setString(i, recherche);
            }
            ResultSet result = statement.executeQuery();

            DefaultTableModel tableModel = (DefaultTableModel) tableUtilisateurs.getModel();
            tableModel.setRowCount(0);

            while (result.next()) {
                Object[] util = new Object[9];
                util[0] = result.getString("id");
                util[1] = result.getString("nom");
                util[2] = result.getString("prenom");
                util[3] = result.getString("login");
                util[4] = result.getString("mdp");
                util[5] = result.getString("adresse");
                util[6] = result.getString("cp");
                util[7] = result.getString("ville");
                util[8] = result.getDate("dateEmbauche");

                tableModel.addRow(util);
            }
        } catch (SQLException ex) {
            Logger.getLogger(AccesBdD.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_jTextRechercheActionPerformed

