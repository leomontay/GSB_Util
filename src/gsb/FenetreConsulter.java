    private void listerUtilisateurs(){
        ArrayList<Utilisateur> util = utilDAO.getLesUtilisateurs(); 
        DefaultTableModel tableModel = (DefaultTableModel)tableUtilisateurs.getModel();
        tableModel.setRowCount(0);

        if (!util.isEmpty()){
            for (Utilisateur u1 : util) {
                Object[] Utilisateur = new Object[8];
                Utilisateur[0]=u1.getId();
                Utilisateur[1]=u1.getNom();
                Utilisateur[2]=u1.getPrenom();
                Utilisateur[3]=u1.getLogin();
                Utilisateur[4]=u1.getAdresse();
                Utilisateur[5]=u1.getCp();
                Utilisateur[6]=u1.getVille();
                Utilisateur[7]=u1.getDateEmbauche();
                tableModel.addRow(Utilisateur);
            }
        }
        tableUtilisateurs.setModel(tableModel);
    }

